// 派活时送给每个 agent 的首条消息。
//
// **跨进程的团队没有入职这回事** —— 每个 agent 是一个全新的 CLI 进程，
// 它对「自己是谁、东西写哪、卡住了怎么办」一无所知，而我们只有这一次机会告诉它：
// 之后就没有 SendMessage 能补充了（那是 CCteam 那种同进程架构才有的通道）。
// 所以这条消息要一次把工作约定说完。
//
// 内容参考 CCteam-creator 的 onboarding 模板，但只搬得动的那部分：
// 它那套「收到任务先确认」「完成汇报发 SendMessage」「有疑问问 team-lead」
// 全部依赖双向消息通道，我们没有。对应改成落盘 —— 疑问写进 findings 的 BLOCKED 段，
// 结论写进 findings，主 agent 收活时一起读。
//
// 抽成纯函数是为了能测：这段文字里有几处**必须和代码保持一致**的约定
// （产出路径要用它自己的 role、「不能再派活」要和 mcpHandler 里那道硬拦对得上），
// 内联在字符串拼接里没人守得住。

export interface BriefInput {
  role: string
  /** 这一批要达成什么 —— 让 agent 知道自己这块在整体里的位置 */
  goal: string
  /** 派给它的具体任务 */
  task: string
}

/**
 * 组一条派活简报。
 *
 * 排序是有讲究的：**任务放在最前面**，纪律在后。反过来写的话，一段长约定会把
 * 真正要做的事挤到注意力之外 —— 这跟 CCteam 那条「目标要出现在文档末尾才进得了
 * 注意力窗口」是同一个现象的两面：首条消息里，开头和结尾都是强位置，中间最弱。
 * 所以任务在开头，最硬的两条约束在结尾。
 */
export function briefFor({ role, goal, task }: BriefInput): string {
  const dir = `.plans/${role}/`
  return [
    `你是这次协作里的 \`${role}\`。`,
    ``,
    `**这一批的目标**：${goal}`,
    `**你负责**：${task}`,
    ``,
    `## 产出`,
    ``,
    `写到 \`${dir}\` 下，别碰别人的目录：`,
    ``,
    `- \`findings.md\` —— 你的结论。**这是主 agent 唯一会读的东西**`,
    `- \`progress.md\` —— 过程：做了什么、下一步、卡在哪`,
    ``,
    `**每做完约 2 次搜索/读取就更新一次 findings.md。** 多步搜索的结果极容易在上下文里`,
    `丢掉 —— 你的上下文是易失的，文件才是持久的，写下来才算真的记住。`,
    ``,
    `## 结论怎么写`,
    ``,
    `不要只说「做完了」。每条都要让人不看你的原始材料就能判断：`,
    ``,
    `- **判据**：你凭什么这么说`,
    `- **证据**：文件:行号 / 命令输出 / 实测数据`,
    `- **边界**：你没做什么、这条结论在什么情况下不成立 —— 这项最容易漏，`,
    `  也最容易让人高估你的覆盖面`,
    ``,
    `如果你推翻了任务里的某个前提，或者发现结论之间有分歧，**显式写出来**，不要替人抹平。`,
    ``,
    `## 卡住了怎么办`,
    ``,
    `同一个错误第 2 次出现就换方案，别重复同一个操作；第 3 次还不行就停下来重新审视假设。`,
    `每次失败在 progress.md 追加一行：试了什么 → 结果 → 下次换什么。`,
    ``,
    `真过不去，在 findings.md 里开一段 \`## BLOCKED\`，写清卡在哪、缺什么。`,
    `**不要静默跳过，也不要猜一个答案填上去** —— 主 agent 宁可收到「这块没做成」，`,
    `也不要收到一个看起来完成、实际编出来的结论。`,
    ``,
    `每做约 10 次工具调用停一下，回头看看还是不是在做任务里那件事。跑偏了在 progress.md`,
    `记一句原因。（工具调用多了模型会开始忘记最初的目标，这一步是对抗它的。）`,
    ``,
    `## 两条硬约定`,
    ``,
    `1. **你不能再派活。** 你是团队成员，不是编排者 —— 系统会拒绝你调 \`team_spawn\`。`,
    `   需要的东西超出这份任务，写进 findings.md 说明「这块需要谁来补」，主 agent 收活时会看到。`,
    `2. **通知留给主 agent。** 你调 \`notify\` 会被拦掉 —— 几个人各响一次会把用户的提示区淹掉。`,
    `   用户在团队面板上看得到你这一行的状态。`,
    ``,
    `干完在最后一条消息里用一句话说清结论，正文仍以 \`${dir}findings.md\` 为准。`
  ].join('\n')
}
