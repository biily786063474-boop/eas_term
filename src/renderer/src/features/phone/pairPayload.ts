// 二维码里装什么。**纯函数** —— 因为它有一条硬约束：编出来必须装得下，
// 而装不下的表现是「界面上没有二维码」，一个不看代码就查不出的空白。
//
// ── 只装「必须走带外通道」的东西 ────────────────────────────────────
// 二维码是这条链路上唯一的**带外通道**：它从屏幕直接进摄像头，
// 不经过网络，所以是唯一一个中间人碰不到的环节。
// 那么只有真正需要这个性质的东西才配占它的位置：
//
//   c  配对码   —— 一次性，60 秒
//   p  指纹     —— 手机以后就认这一把公钥。**这条是钉死的全部意义**：
//                  从网络上取它就等于让中间人有机会换掉它
//   s  TLS 端口 —— 不是秘密，但没有它 app 不知道该敲哪个门
//
// **其余一律不装**（隧道门牌号、其它候选地址……）：它们等 TLS 建起来之后
// 从**已认证的连接**上取，那时候有指纹保护，跟装在二维码里一样安全，
// 却不占带外通道的位置。
//
// ── 为什么这个约束是硬的 ───────────────────────────────────────────
// 自带的编码器只到版本 7（121 字节），停在这里是有意的 ——
// 从版本 8 起块不再等长，单组写法编出来的码是坏的（见 qr.ts 文件头）。
// 所以载荷设计要**主动往 121 以内收**，而不是等哪天扫不出来才发现。

/** 编码器的上限。超了 encode() 返回 null，界面上就是一片空白。 */
export const QR_MAX_BYTES = 121

export interface PairInfo {
  /** 明文口，形如 http://192.168.1.20:51240 */
  url: string
  code: string
  /** 公钥指纹（43 字符）。没有身份时为 null —— 那种情况下只能走浏览器 */
  pin: string | null
  /** TLS 口，形如 https://192.168.1.20:51241。起不来时为 null */
  secureUrl: string | null
}

/**
 * 二维码里那串东西。
 *
 * **形状仍然是一个可以直接打开的 URL** —— 用手机相机扫它会打开浏览器版，
 * 那条路今天就在用，不能因为加了 app 就断掉。app 则从查询参数里读它要的东西，
 * 认不得的参数浏览器会原样忽略。一张码同时服务两种客户端。
 */
export function pairUrl(info: PairInfo): string {
  let s = `${info.url}/?c=${info.code}`
  if (info.pin) s += `&p=${info.pin}`
  const port = info.secureUrl ? /:(\d+)$/.exec(info.secureUrl)?.[1] : null
  if (port) s += `&s=${port}`
  return s
}

/** 装得下吗。**界面在画之前应该问一次** —— 装不下要说出来，不是画个空白。 */
export function fitsInQr(s: string): boolean {
  return new TextEncoder().encode(s).length <= QR_MAX_BYTES
}
