// 「跳过去看看」时该用多大的缩放。
//
// ── 这个函数为什么存在 ─────────────────────────────────────────────
// 通知（灵动岛 / 待处理列表 / 抽屉）点过去时，原来是**保持当前缩放只平移**。
// 于是在稍大的缩放下会出现：节点比视口还高，聚焦完屏幕上全是那一个终端，
// 四周一点空白都不剩 —— 用户既看不到终端的全貌，**也没有地方能抓着拖画布**
// （按下去全落在 xterm 里）。2026-08-31 用户报的就是这个。
//
// ── 两条不能违反的规则 ────────────────────────────────────────────
// 1. **只缩小，不放大**。聚焦一个小节点不该把画布怼到 2.2 倍 ——
//    用户对当前缩放是有预期的，我们只在「装不下」时才动它。
// 2. **四周必须留白**。留白不只是好看：那是唯一能抓着平移画布的地方。
//
// 合法区间的钳制**不在这里做** —— setViewport 已经过一道 clampScale，
// 在这儿再钳一次就是两个地方各说各的，改上限时必然漏掉一处。
// 这个文件只回答「多大才装得下」，零依赖、能单独跑测试。

/** 节点四周留出多少屏幕像素。**同时是「能抓着拖画布」的那圈地方** */
export const FIT_PAD = 48

export function fitScale(
  node: { w: number; h: number },
  view: { w: number; h: number },
  current: number,
  pad = FIT_PAD
): number {
  // 尺寸不可信（0 / 负数 / NaN）时什么都不做，别拿一个算不出来的数去改用户的画布
  if (!(node.w > 0 && node.h > 0 && view.w > 0 && view.h > 0) || !Number.isFinite(current)) {
    return current
  }
  // 窗口窄到连留白都放不下时，留白按比例缩水而不是变成负数
  // （负数会让 fit 变负，clamp 之后是 0.2，画面直接跳到最小缩放）
  const p = Math.min(pad, view.w / 4, view.h / 4)
  const fit = Math.min((view.w - p * 2) / node.w, (view.h - p * 2) / node.h)
  // 只缩小不放大：装得下就保持用户当前的缩放
  return Math.min(current, fit)
}
