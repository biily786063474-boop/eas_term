// 辞典的两级分类表：一级 = 你想干什么，二级 = 具体手法。
//
// ── 为什么这里也要有一份 ────────────────────────────────────────────
// 分类表的正本在 dictionary-bundle.json（那份还带每个二级的一句说明，界面用）。
// 但 **dict_add 的校验跑在主进程**，而 bundle 是渲染层的 import，主进程够不着。
// 没有校验的话，agent 写错一个二级名不会报错，词条会落在一个不存在的分类下 ——
// 界面上一级二级都筛不到它，等于静默丢失。
//
// 两份数据必然要防分叉：`dictTaxonomy.test.ts` 断言这份和 bundle 里那份逐字相同，
// 改了一边忘了另一边，测试当场红。
