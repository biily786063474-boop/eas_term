/** 一级分类名（界面导航按这个顺序渲染） */
export const DICT_CAT1 = Object.keys(DICT_TAXONOMY)

/**
 * 老一级名 → 新一级名。
 *
 * **这张表不能删。** 用户机器上已装的 skill 还在按 2026-08-31 那版的一级名调
 * `dict_add`，删了的话它们会被当场拒绝；更坏的是 `readUser()` 里那句
 * `isValidCat(t.cat1, t.cat2)` 会对已存的自建词条返回 false，
 * 而 `dict:add` 是「整个读出来再整个写回去」—— 于是**下次加词就把老词条的
 * 分类洗掉一遍**（2026-08-31 加 cat1/cat2 时正是这么踩的，见 main/dict.ts）。
 */
const LEGACY_CAT1: Readonly<Record<string, string>> = {
  '输入与表单': '前端 · 组件',
  '列表与滚动': '前端 · 组件',
  '反馈与提示': '前端 · 组件',
  '材质与质感': '前端 · 视觉',
  '版式与风格': '前端 · 视觉',
  '转场与入场': '前端 · 动效',
  '运动规律': '前端 · 动效',
  '手势与拖拽': '前端 · 动效',
  '加载与等待': '前端 · 数据'
}

/**
 * 把一对 (cat1, cat2) 归一成**当前表里的**一级名。
 *
 * @returns 归一后的一级名；这对分类不成立时返回 `null`。
 *          老一级名也认（见 `LEGACY_CAT1`），返回的是**新名** ——
 *          调用方应当存这个返回值，而不是存用户传进来的那个，
 *          否则老名会一直在库里留着，分类表就永远清不干净。
 */
export function normalizeCat1(cat1: unknown, cat2: unknown): string | null {
  if (typeof cat1 !== 'string' || typeof cat2 !== 'string') return null
  if (DICT_TAXONOMY[cat1]?.includes(cat2)) return cat1
  const mapped = LEGACY_CAT1[cat1]
  if (mapped && DICT_TAXONOMY[mapped]?.includes(cat2)) return mapped
  return null
}

/** 这个一级下有没有这个二级。两个都要给，只给一个不算归好类 */
export function isValidCat(cat1: unknown, cat2: unknown): boolean {
  return normalizeCat1(cat1, cat2) !== null
}
