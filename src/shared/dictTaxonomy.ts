/** 一级分类名（界面导航按这个顺序渲染） */
export const DICT_CAT1 = Object.keys(DICT_TAXONOMY)

/** 这个一级下有没有这个二级。两个都要给，只给一个不算归好类 */
export function isValidCat(cat1: unknown, cat2: unknown): boolean {
  if (typeof cat1 !== 'string' || typeof cat2 !== 'string') return false
  return DICT_TAXONOMY[cat1]?.includes(cat2) ?? false
}
