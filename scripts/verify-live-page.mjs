import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import http from 'node:http'
import { spawn } from 'node:child_process'

const root = process.cwd()
const output = path.join(root, 'docs/verification/live-page')
fs.mkdirSync(output, { recursive: true })
const profile = fs.mkdtempSync(path.join(os.tmpdir(), 'eas-live-page-profile-'))
const project = fs.mkdtempSync(path.join(os.tmpdir(), 'eas-live-page-project-'))
fs.writeFileSync(path.join(profile, 'projects.json'), JSON.stringify([{ id: 'live-page-project', name: '页面验收', path: project }]))
fs.writeFileSync(path.join(profile, 'prefs.json'), JSON.stringify({ autoUpdateCheck: false, telemetry: false, island: false }))
const server = http.createServer((_req, res) => { res.setHeader('Content-Type', 'text/html; charset=utf-8'); res.end('<!doctype html><html><title>Live Page Fixture</title><body style="background:#dce9ff;font:24px sans-serif"><h1>LIVE PAGE VERIFIED</h1><input id="name" placeholder="Name"><button id="action" onclick="document.querySelector(\'h1\').textContent=\'CLICKED\'">Click me</button></body></html>') })
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
const url = 'http://127.0.0.1:' + server.address().port + '/'
const executable = process.env.EAS_VERIFY_ELECTRON || path.join(root, 'node_modules/electron/dist/Electron.app/Contents/MacOS/Electron')
const env = { ...process.env, EAS_VERIFY: '1' }
for (const name of Object.keys(env)) if (name.startsWith('EAS_TERM_') || name.startsWith('EAS_CAPABILITY_')) delete env[name]
const policy = '(version 1) (allow default) ' + ['.codex', '.claude', '.claude.json', '.eas', '.dsh'].map(n => '(deny file-read* file-write* (subpath ' + JSON.stringify(path.join(os.homedir(), n)) + '))').join(' ')
const child = spawn('/usr/bin/sandbox-exec', ['-p', policy, executable, root, '--no-sandbox', '--remote-debugging-port=0', '--user-data-dir=' + profile], { env, stdio: ['ignore', 'pipe', 'pipe'] })
let logs = ''
child.stdout.on('data', x => logs += x)
child.stderr.on('data', x => logs += x)
const wait = ms => new Promise(resolve => setTimeout(resolve, ms))
const until = async fn => { for (let i = 0; i < 150; i++) { const value = await fn(); if (value) return value; await wait(100) } throw Error('Timed out') }
const checks = []
function check(value, name) { if (!value) throw Error(name); checks.push(name) }
let ws
try {
  const port = await until(async () => { try { return Number(fs.readFileSync(path.join(profile, 'DevToolsActivePort'), 'utf8').split('\n')[0]) } catch { if (child.exitCode !== null) throw Error(logs.slice(-2000)) } })
  const targets = async () => await (await fetch('http://127.0.0.1:' + port + '/json/list')).json()
  const target = await until(async () => (await targets()).find(item => item.type === 'page' && item.title === 'Eas-Term'))
  ws = new WebSocket(target.webSocketDebuggerUrl)
  await new Promise((resolve, reject) => { ws.addEventListener('open', resolve, { once: true }); ws.addEventListener('error', reject, { once: true }) })
  let id = 0
  const pending = new Map()
  ws.addEventListener('message', e => { const msg = JSON.parse(e.data); const callback = pending.get(msg.id); if (callback) { pending.delete(msg.id); msg.error ? callback.reject(Error(JSON.stringify(msg.error))) : callback.resolve(msg.result) } })
  const send = (method, params = {}) => new Promise((resolve, reject) => { const key = ++id; pending.set(key, { resolve, reject }); ws.send(JSON.stringify({ id: key, method, params })) })
  const evaluate = async expression => { const result = await send('Runtime.evaluate', { expression, returnByValue: true, awaitPromise: true }); if (result.exceptionDetails) throw Error(result.exceptionDetails.exception?.description || result.exceptionDetails.text); return result.result?.value }
  const motionSamples = async selector => evaluate("new Promise(resolve=>{const samples=[],start=performance.now(),panel=document.querySelector('.live-page-drawer');let done=false;const finish=()=>{if(!done){done=true;resolve(samples)}};setTimeout(finish,1200);document.querySelector(" + JSON.stringify(selector) + ").click();const tick=()=>{if(done)return;samples.push(new DOMMatrix(getComputedStyle(panel).transform).m41);if(performance.now()-start<580)requestAnimationFrame(tick);else finish()};requestAnimationFrame(tick)})")
  const endpoint = await until(async () => { try { return JSON.parse(fs.readFileSync(path.join(profile, 'mcp-endpoint.json'), 'utf8')) } catch { return null } })
  const invoke = async (tool, args, leafId) => (await (await fetch('http://127.0.0.1:' + endpoint.port + '/invoke', { method: 'POST', headers: { 'x-eas-token': endpoint.token, 'content-type': 'application/json' }, body: JSON.stringify({ tool, args, ctx: { agentLeafId: leafId } }) })).json())
  await until(() => evaluate('!!window.__store && !!window.api?.livePage'))
  await evaluate("window.__store.getState().setViewMode('split')")
  await evaluate('window.api.livePage.open(' + JSON.stringify(url) + ", 'verify-leaf')")
  await until(() => evaluate("!!document.querySelector('.live-page-drawer.is-open .live-page-surface img')"))
  check(await evaluate("document.querySelector('.live-page-drawer .live-page-titles strong')?.textContent === 'Live Page Fixture'"), '分屏右侧抽屉展示真实页面标题')
  check(await evaluate("getComputedStyle(document.querySelector('.live-page-drawer')).transitionDuration.includes('0.44s')"), '抽屉具备平滑位移动效')
  check(await evaluate("document.querySelector('.live-page-drawer img')?.naturalWidth > 0"), '隐藏浏览器画面捕获成功')
  check(await evaluate("window.api.livePage.open('https://example.com','bad').then(()=>false,()=>true)"), '阻止外网地址进入观察窗')
  check(await evaluate("window.api.livePage.open('file:///etc/hosts','bad').then(()=>false,()=>true)"), '阻止本地文件绕过授权')
  await wait(500)
  const shot = await send('Page.captureScreenshot', { format: 'png' })
  fs.writeFileSync(path.join(output, 'split-drawer.png'), Buffer.from(shot.data, 'base64'))
  const leavingSamples = await motionSamples('.live-page-header button[aria-label="收起预览"]')
  check(await until(() => evaluate("!document.querySelector('.live-page-drawer').classList.contains('is-open')")), '收起抽屉')
  const hiddenX = leavingSamples.at(-1)
  check(leavingSamples.some(x => x > 1 && x < hiddenX - 1), '退出时实际逐帧滑出而非闪现')
  check(await evaluate("!!document.querySelector('.live-page-reopen')"), '保留重新打开入口')
  const enteringSamples = await motionSamples('.live-page-reopen')
  check(await until(() => evaluate("document.querySelector('.live-page-drawer').classList.contains('is-open')")), '重新打开原会话')
  check(enteringSamples.some(x => x > 1 && x < hiddenX - 1), '进入时实际逐帧滑入而非闪现')
  await evaluate("window.api.livePage.close('leaf:verify-leaf')")
  check(await until(() => evaluate("!document.querySelector('.live-page-drawer').classList.contains('is-open')")), '结束页面观察')
  const leaf = await evaluate("(async()=>{const s=window.__store.getState();s.setViewMode('canvas');await s.addProjectFrame('live-page-project',80,80);const frame=window.__store.getState().canvas.frames[0];await window.__store.getState().addAgentNode(frame.id,{cli:'codex'});return window.__store.getState().canvas.frames.find(f=>f.id===frame.id)?.nodes.find(n=>n.leafId)?.leafId})()")
  check(!!leaf, '画板创建 AI 对话节点')
  await evaluate('window.api.livePage.open(' + JSON.stringify(url) + ',' + JSON.stringify(leaf) + ')')
  check(await until(() => evaluate("!!document.querySelector('.live-page-chat-host.has-live-page .live-page-inline img')")), '画板只在对应 AI 对话内分屏')
  await evaluate("document.querySelector('.live-page-chat-host').style.width='500px'")
  check(await until(() => evaluate("getComputedStyle(document.querySelector('.live-page-chat-host')).flexDirection==='column'")), '窄画板节点改为上下布局')
  await evaluate("document.querySelector('.live-page-chat-host').style.width=''")
  await send('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-motion', value: 'reduce' }] })
  check(await evaluate("getComputedStyle(document.querySelector('.live-page-inline')).transitionDuration.split(',').every(x=>parseFloat(x)<=0.001)"), '减少动效偏好关闭位移动画')
  await send('Emulation.setEmulatedMedia', { features: [] })
  check((await invoke('page_live_inspect', {}, leaf)).data?.title === 'Live Page Fixture', 'MCP 工具读取真实开发页面')
  check((await invoke('page_live_inspect', {}, 'different-leaf')).ok === false, '其他 AI 会话不能读取该页面')
  check((await invoke('page_live_type', { selector: '#name', text: 'Eas-Term' }, leaf)).ok, 'MCP 工具可输入开发页面')
  check((await invoke('page_live_click', { selector: '#action' }, leaf)).ok, 'MCP 工具可点击开发页面')
  check((await invoke('page_live_inspect', {}, leaf)).data?.text?.includes('CLICKED'), '点击结果可被同会话读取')
  await evaluate("window.__store.getState().setViewMode('split')")
  check(await until(() => evaluate("!!document.querySelector('.live-page-drawer.is-open')")), '切到分屏沿用同一观察会话')
  check(await until(() => evaluate("(()=>{const h=document.querySelector('.live-page-chat-host');return !!h && !h.classList.contains('has-live-page') && h.querySelector('.live-page-chat-content').getBoundingClientRect().width>=h.getBoundingClientRect().width-2})()")), '分屏 AI 对话保持完整宽度')
  await evaluate("window.__store.getState().setViewMode('canvas')")
  check(await until(() => evaluate("!!document.querySelector('.live-page-chat-host.has-live-page')")), '切回画板恢复对话内预览')
  await wait(500)
  const canvasShot = await send('Page.captureScreenshot', { format: 'png' })
  fs.writeFileSync(path.join(output, 'canvas-inline.png'), Buffer.from(canvasShot.data, 'base64'))
  await evaluate("document.querySelector('.live-page-inline .live-page-header button[aria-label=\"在独立窗口中打开\"]').click()")
  check(await until(() => evaluate("!document.querySelector('.live-page-chat-host').classList.contains('has-live-page')")), '独立窗口弹出后画板分屏收起')
  check((await evaluate('window.api.livePage.snapshot()'))[0]?.popout === true, '独立窗口沿用同一会话')
  await evaluate("document.querySelector('.live-page-chat-host .live-page-reopen').click()")
  check(await until(() => evaluate("!!document.querySelector('.live-page-chat-host.has-live-page .live-page-inline img')")), '从独立窗口返回同一画板预览')
  await evaluate('window.api.livePage.close(' + JSON.stringify('leaf:' + leaf) + ')')
  fs.writeFileSync(path.join(output, 'result.json'), JSON.stringify({ passed: true, checks }, null, 2))
  fs.rmSync(path.join(output, 'failure.json'), { force: true })
  console.log(JSON.stringify({ passed: true, checks }, null, 2))
} catch (error) {
  console.error(error)
  process.exitCode = 1
  fs.writeFileSync(path.join(output, 'failure.json'), JSON.stringify({ checks, error: String(error) }, null, 2))
} finally {
  ws?.close()
  child.kill('SIGTERM')
  server.close()
  await Promise.race([new Promise(resolve => child.once('exit', resolve)), wait(2000)])
  if (child.exitCode === null && child.signalCode === null) child.kill('SIGKILL')
  if (process.exitCode) fs.writeFileSync(path.join(output, 'app.log'), logs)
  else fs.rmSync(path.join(output, 'app.log'), { force: true })
  await fs.promises.rm(profile, { recursive: true, force: true })
  await fs.promises.rm(project, { recursive: true, force: true })
}
